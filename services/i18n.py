# In-memory translation cache for non-precompiled languages / dynamic fallback
_DYNAMIC_UI_CACHE = {}


def get_available_ui_languages():
    """Return all available UI languages with tribal languages prominently tagged."""
    tribal_list = [f"🌿 {l} (Tribal)" for l in TRIBAL_LANG_CODES.keys()]
    indic_list = [l for l in LANG_CODES.keys() if l != "English"]
    return ["English (Default)"] + tribal_list + indic_list


def normalize_ui_language(raw_lang: str) -> str:
    """Normalize raw language string from dropdown to base language name."""
    if not raw_lang:
        return "English"
    if "English" in raw_lang:
        return "English"
    clean = raw_lang.replace("🌿", "").replace("(Tribal)", "").strip()
    return clean


def t(key: str, **kwargs) -> str:
    """
    Retrieve translated text for the current UI language.
    Falls back gracefully to English if translation is unavailable.
    """
    current_ui_raw = st.session_state.get("portal_ui_language", "English")
    lang = normalize_ui_language(current_ui_raw)

    # 1. Exact match in dictionary
    if lang in I18N_DICTIONARY and key in I18N_DICTIONARY[lang]:
        res = I18N_DICTIONARY[lang][key]
        if kwargs:
            try:
                res = res.format(**kwargs)
            except Exception:
                pass
        return res

    # 2. English baseline
    baseline = I18N_DICTIONARY.get("English", {}).get(key, key)
    if lang == "English":
        if kwargs:
            try:
                baseline = baseline.format(**kwargs)
            except Exception:
                pass
        return baseline

    # 3. Dynamic cached fallback for tribal or other Indic languages
    cache_key = f"{lang}_{key}"
    if cache_key in _DYNAMIC_UI_CACHE:
        res = _DYNAMIC_UI_CACHE[cache_key]
        if kwargs:
            try:
                res = res.format(**kwargs)
            except Exception:
                pass
        return res

    # Fallback to English baseline if no dynamic translation available
    if kwargs:
        try:
            baseline = baseline.format(**kwargs)
        except Exception:
            pass
    return baseline
